// Calculate totals
export const getNeetcode150Stats = () => {
  let total = 0;
  let easy = 0;
  let medium = 0;
  let hard = 0;
  let blind = 0;

  neetcode150Categories.forEach(category => {
    total += category.problems.length;
    category.problems.forEach(p => {
      if (p.difficulty === 'Easy') easy++;
      else if (p.difficulty === 'Medium') medium++;
      else if (p.difficulty === 'Hard') hard++;
      if (p.isBlind) blind++;
    });
  });

  return { total, easy, medium, hard, blind, categories: neetcode150Categories.length };
};

export const getProblemById = (id) => {
  for (const category of neetcode150Categories) {
    const problem = category.problems.find(p => p.id === id);
    if (problem) return { ...problem, category: category.name };
  }
  return null;
};
